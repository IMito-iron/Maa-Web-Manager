#!/usr/bin/env node
// Generate apps/server/src/maa-model/form-spec.generated.ts from the Windows reference schema.
// Usage: node scripts/build-form-spec.cjs [schema.json] [out.ts]
// Re-run after regenerating docs/maa-windows-reference/maa-ui-schema.json for a new MAA version;
// the coverage test then reports any option the editor does not handle yet.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const schemaPath = path.resolve(process.argv[2] || path.join(root, 'docs/maa-windows-reference/maa-ui-schema.json'));
const outPath = path.resolve(process.argv[3] || path.join(root, 'apps/server/src/maa-model/form-spec.generated.ts'));
const GUI_TASKS = ['StartUp', 'Recruit', 'Infrast', 'Fight', 'Mall', 'Award', 'Roguelike', 'Custom', 'SwitchTheme'];

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
// Nested localisation keys left in schema labels, resolved with MaaWpfGui v6.21.4
// Res/Localizations/zh-cn.xaml (Game.Operator, Roguelike.StartingCoreChar, TaskQueue.Annihilation.Stage).
const LOCALE_KEYS = {'Game.Operator': '干员', 'Roguelike.StartingCoreChar': '开局干员', 'TaskQueue.Annihilation.Stage': '剿灭关卡'};
const resolveLabel = label => {
  let out = label || '';
  for (let i = 0; i < 3; i++) out = out.replace(/\{key=([A-Za-z.]+)\}/g, (m, k) => LOCALE_KEYS[k] ?? m);
  return out;
};
for (const task of schema.tasks) for (const o of task.options) o.label = resolveLabel(o.label);
const spec = {};
const dispositions = [];
const fieldOf = configKey => {
  const m = /TaskQueue\[i\]\[\$type=\w+\]\.(\w+)$/.exec(configKey || '');
  return m ? m[1] : null;
};

for (const task of schema.tasks) {
  const fields = new Map();
  for (const o of task.options) {
    const field = fieldOf(o.configKey);
    let excluded = null;
    if (!GUI_TASKS.includes(task.id)) excluded = 'task type not modelled (deferred)';
    else if (o.inTaskJson === 'seeGlobal') excluded = 'global setting (preset level or deployment)';
    else if (/ConnectSettings\.Extras/.test(o.configKey || '')) excluded = 'connection extra (deployment)';
    else if (!field) excluded = 'constant / display-only control';
    else if (field === 'IsEnable' || field === 'Name') excluded = 'task list (enable checkbox / rename)';
    else if (o.control === 'none' && field !== 'Seed') excluded = 'internal state, no control';
    if (excluded === 'constant / display-only control' && /\.(IsEnable|Name)$/.test(o.id)) excluded = 'task list (enable checkbox / rename)';
    dispositions.push([o.id, excluded ? null : `${task.id}.${field}`, excluded]);
    if (excluded) continue;
    const f = fields.get(field) || {key: field, label: '', group: o.group, controls: [], visible: [], enabled: [], choices: null, range: null, default: o.default ?? null, paramKey: o.paramKey ?? null, inTaskJson: o.inTaskJson};
    if (!f.label || (/·/.test(f.label) && o.label && !/·/.test(o.label))) f.label = o.label || f.label;
    if (!f.controls.includes(o.control)) f.controls.push(o.control);
    f.visible.push(o.visibleWhen ?? null);
    f.enabled.push(o.enabledWhen ?? null);
    if (f.choices === null && o.choices != null) f.choices = o.choices;
    if (f.range === null && o.range != null) f.range = o.range;
    fields.set(field, f);
  }
  if (!GUI_TASKS.includes(task.id)) continue;
  spec[task.id] = [...fields.values()].map(f => ({...f, visible: [...new Set(f.visible)], enabled: [...new Set(f.enabled)]}));
}

const banner = `// GENERATED by scripts/build-form-spec.cjs from ${path.relative(root, schemaPath).replace(/\\/g, '/')}\n`
  + `// (MAA ${schema.maaVersion}, ${schema.sourceTag}). Do not edit by hand.\n`
  + `/* eslint-disable */\n`;
const body = `export interface SpecField {\n  key: string; label: string; group: string; controls: string[];\n  /** CalcBinding expressions; a field is visible if any is null or true. */\n  visible: (string | null)[]; enabled: (string | null)[];\n  choices: any; range: {Minimum?: string; Maximum?: string} | null; default: any; paramKey: string | null; inTaskJson: unknown;\n}\n`
  + `export const MAA_VERSION = ${JSON.stringify(schema.maaVersion)};\n`
  + `export const FORM_SPEC: Record<string, SpecField[]> = ${JSON.stringify(spec, null, 1)};\n`
  + `/** Every schema option: [option id, spec field or null, exclusion reason or null]. */\n`
  + `export const SCHEMA_OPTIONS: [string, string | null, string | null][] = ${JSON.stringify(dispositions)};\n`;
fs.writeFileSync(outPath, banner + body);
console.log(`wrote ${path.relative(root, outPath)}: ${Object.values(spec).reduce((n, v) => n + v.length, 0)} fields, ${dispositions.length} options`);

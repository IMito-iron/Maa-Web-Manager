/** Interpolates `{name}` placeholders; unknown placeholders are left untouched. */
export function format(template: string, params?: Params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in params ? String(params[key]) : match));
}

/**
 * The one entry point components use: the Chinese text is both the key and the fallback, so a
 * missing Japanese string renders Chinese rather than a placeholder.
 */
export function translate(locale: Locale, text: string, params?: Params) {
  const template = locale === 'zh' ? text : JA[text] ?? text;
  return format(template, params);
}

/** The locale chosen in this browser, for text produced outside React (see api.ts). */
export function currentLocale(): Locale {
  try { return detectLocale(localStorage.getItem(LOCALE_STORAGE_KEY)); } catch { return DEFAULT_LOCALE; }
}

/** Stored choice wins; otherwise the browser's languages; otherwise Chinese. */
export function detectLocale(stored?: string | null, languages: readonly string[] = []): Locale {
  if (stored && (LOCALES as readonly string[]).includes(stored)) return stored as Locale;
  for (const language of languages) {
    const base = String(language).toLowerCase().split('-')[0];
    if ((LOCALES as readonly string[]).includes(base)) return base as Locale;
  }
  return DEFAULT_LOCALE;
}

/** Chinese strings the Japanese dictionary does not cover yet (used by the coverage test). */
export function missingTranslations(texts: Iterable<string>) {
  const missing: string[] = [];
  for (const text of texts) {
    if (/[\u4e00-\u9fff]/.test(text) && !(text in JA) && !missing.includes(text)) missing.push(text);
  }
  return missing;
}
